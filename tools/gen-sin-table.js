// Generates engine/core/sin-table.js: a 4096-entry sine table in Q14 (16384 = 1.0).
// The table is generated once and committed as integers, so the simulation never evaluates
// Math.sin at runtime (docs/engine/09-determinism-coop.md#fixed-point-formats).
// Usage: node tools/gen-sin-table.js
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const N = 4096;
const ONE = 16384;
const values = new Int32Array(N);
for (let i = 0; i < N; i++) values[i] = Math.round(Math.sin((2 * Math.PI * i) / N) * ONE);

// FNV-1a over the little-endian bytes, used by a unit test to pin the table.
let hash = 0x811c9dc5;
const bytes = new Uint8Array(values.buffer);
for (const b of bytes) hash = Math.imul(hash ^ b, 0x01000193) >>> 0;

const rows = [];
for (let i = 0; i < N; i += 16) rows.push(`  ${Array.from(values.subarray(i, i + 16)).join(', ')},`);
const src = `// @ts-check
// GENERATED by tools/gen-sin-table.js. Do not edit.
// Sine table: 4096 entries, one per 16 binary-angle units (65,536 = 360 degrees), Q14 (16,384 = 1.0).

export const SIN_TABLE_SIZE = ${N};
/** FNV-1a hash of the table bytes (little-endian Int32). */
export const SIN_TABLE_HASH = 0x${hash.toString(16).padStart(8, '0')};
export const SIN_TABLE_Q14 = new Int32Array([
${rows.join('\n')}
]);
`;
const out = resolve(import.meta.dirname, '../engine/core/sin-table.js');
writeFileSync(out, src);
console.log(`wrote ${out} (hash 0x${hash.toString(16)})`);
